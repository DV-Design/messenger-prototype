#!/usr/bin/env bash
#
# Reproducible PUSH-enabled Android release build.
#
# Root cause this helper guards against: app.config.ts is evaluated by Expo
# prebuild AND again by the Gradle/React Native JS bundle step. If
# MESSENGER_GOOGLE_SERVICES_FILE is exported only for prebuild, the packaged
# assets/app.config ends up with extra.nativeFcmConfigured=false even though
# android/app/google-services.json exists. This script exports the variable
# once, before every Expo/Gradle invocation, and then verifies the constants
# actually packaged inside the APK.
#
# It does not copy, publish, or inspect the client config contents.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd -P)"
MOBILE_DIR="$REPO_ROOT/apps/mobile"
ANDROID_DIR="$MOBILE_DIR/android"
APK_REL="apps/mobile/android/app/build/outputs/apk/release/app-release.apk"
APK_PATH="$REPO_ROOT/$APK_REL"

die() {
  printf 'build:apk: ERROR: %s\n' "$*" >&2
  exit 1
}

# ---------------------------------------------------------------------------
# Fail-fast validation. Nothing below this block may run when config is bad.
# ---------------------------------------------------------------------------

[[ -d "$MOBILE_DIR" ]] || die "mobile app directory not found: apps/mobile"
[[ -f "$MOBILE_DIR/app.config.ts" ]] || die "app.config.ts not found in apps/mobile"

SERVICES_FILE="${MESSENGER_GOOGLE_SERVICES_FILE:-}"
if [[ -z "$SERVICES_FILE" ]]; then
  die "MESSENGER_GOOGLE_SERVICES_FILE is not set. Pass an absolute path to the client Firebase config (for example google-services.json) located outside the repo."
fi

[[ "$SERVICES_FILE" = /* ]] || die "MESSENGER_GOOGLE_SERVICES_FILE must be an absolute path."
[[ -f "$SERVICES_FILE" ]] || die "MESSENGER_GOOGLE_SERVICES_FILE is not a regular file."
[[ -r "$SERVICES_FILE" ]] || die "MESSENGER_GOOGLE_SERVICES_FILE is not readable."

SERVICES_BASENAME="$(basename "$SERVICES_FILE")"
case "$SERVICES_BASENAME" in
  *.json) ;;
  *) die "MESSENGER_GOOGLE_SERVICES_FILE must point to a JSON client config file." ;;
esac

# Reject the server-side Firebase Admin service-account by name only.
# The file contents are never read or printed by this script.
SERVICES_BASENAME_LOWER="$(printf '%s' "$SERVICES_BASENAME" | tr '[:upper:]' '[:lower:]')"
case "$SERVICES_BASENAME_LOWER" in
  *admin*|*service-account*|*service_account*)
    die "MESSENGER_GOOGLE_SERVICES_FILE looks like server/admin credentials. Use only the client Firebase config."
    ;;
esac

if command -v realpath >/dev/null 2>&1; then
  SERVICES_FILE_REAL="$(realpath "$SERVICES_FILE")"
else
  SERVICES_FILE_REAL="$(cd "$(dirname "$SERVICES_FILE")" && pwd -P)/$SERVICES_BASENAME"
fi

case "$SERVICES_FILE_REAL" in
  "$REPO_ROOT"|"$REPO_ROOT"/*)
    die "MESSENGER_GOOGLE_SERVICES_FILE must be outside the repository."
    ;;
esac

command -v node >/dev/null 2>&1 || die "node is required."
command -v npx >/dev/null 2>&1 || die "npx (from Node/npm) is required."
command -v unzip >/dev/null 2>&1 || die "unzip is required."

# The variable is exported once and therefore inherited by every Expo and
# Gradle child process below, including the JS bundle task that re-evaluates
# app.config.ts. JAVA_HOME / ANDROID_HOME are intentionally inherited as-is.
export MESSENGER_GOOGLE_SERVICES_FILE="$SERVICES_FILE"

# Read the expected version/versionCode from the current Expo config instead of
# hardcoding them. This also confirms that app.config.ts can be evaluated.
EXPECTED_CONFIG_JSON="$(cd "$MOBILE_DIR" && npx --no-install expo config --type public --json)"
EXPECTED_CONFIG_JSON="$EXPECTED_CONFIG_JSON" node -e '
  const c = JSON.parse(process.env.EXPECTED_CONFIG_JSON);
  if (!c.version) throw new Error("current Expo config has no version");
  if (!c.android || c.android.versionCode === undefined) throw new Error("current Expo config has no android.versionCode");
' || die "could not read version/android.versionCode from the current Expo config."

printf 'build:apk: client config path validated (contents not read).\n'
printf 'build:apk: repo root: %s\n' "$REPO_ROOT"

# ---------------------------------------------------------------------------
# Build stages. The exported MESSENGER_GOOGLE_SERVICES_FILE is present in all.
# ---------------------------------------------------------------------------

printf 'build:apk: [1/3] expo prebuild (android)\n'
(
  cd "$MOBILE_DIR"
  npx --no-install expo prebuild --platform android --no-install
)

[[ -x "$ANDROID_DIR/gradlew" ]] || die "android/gradlew not found after prebuild."
[[ -f "$ANDROID_DIR/app/google-services.json" ]] || die "android/app/google-services.json was not generated by prebuild; native FCM would be missing."

printf 'build:apk: [2/3] Gradle JS bundle (release)\n'
(
  cd "$ANDROID_DIR"
  ./gradlew :app:createBundleReleaseJsAndAssets \
    --rerun-tasks \
    -PreactNativeArchitectures=arm64-v8a \
    --no-daemon
)

printf 'build:apk: [3/3] Gradle assembleRelease\n'
(
  cd "$ANDROID_DIR"
  ./gradlew :app:assembleRelease \
    -PreactNativeArchitectures=arm64-v8a \
    --no-daemon
)

[[ -f "$APK_PATH" ]] || die "release APK not found: $APK_REL"

# ---------------------------------------------------------------------------
# Packaged-constants gate. Reads only assets/app.config from the APK.
# ---------------------------------------------------------------------------

printf 'build:apk: verifying packaged assets/app.config\n'
APK_PATH="$APK_PATH" APK_REL="$APK_REL" EXPECTED_CONFIG_JSON="$EXPECTED_CONFIG_JSON" node <<'NODE'
const fs = require('fs');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const apk = process.env.APK_PATH;
const apkRel = process.env.APK_REL;
const expected = JSON.parse(process.env.EXPECTED_CONFIG_JSON);

let raw;
try {
  raw = execFileSync('unzip', ['-p', apk, 'assets/app.config'], {
    maxBuffer: 8 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch (error) {
  console.error('build:apk: ERROR: could not extract assets/app.config from the APK.');
  process.exit(1);
}

let packaged;
try {
  packaged = JSON.parse(raw.toString('utf8'));
} catch (error) {
  console.error('build:apk: ERROR: assets/app.config in the APK is not valid JSON.');
  process.exit(1);
}

const actual = {
  nativeFcmConfigured: packaged.extra ? packaged.extra.nativeFcmConfigured : undefined,
  version: packaged.version,
  versionCode: packaged.android ? packaged.android.versionCode : undefined,
};
const want = {
  nativeFcmConfigured: true,
  version: expected.version,
  versionCode: expected.android.versionCode,
};

const problems = [];
if (actual.nativeFcmConfigured !== want.nativeFcmConfigured) {
  problems.push(`extra.nativeFcmConfigured is ${JSON.stringify(actual.nativeFcmConfigured)}, expected true (JS push would be disabled)`);
}
if (actual.version !== want.version) {
  problems.push(`version is ${JSON.stringify(actual.version)}, expected ${JSON.stringify(want.version)}`);
}
if (actual.versionCode !== want.versionCode) {
  problems.push(`android.versionCode is ${JSON.stringify(actual.versionCode)}, expected ${JSON.stringify(want.versionCode)}`);
}

if (problems.length > 0) {
  console.error('build:apk: ERROR: packaged constants do not match the current config:');
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const sha256 = crypto.createHash('sha256').update(fs.readFileSync(apk)).digest('hex');
console.log(JSON.stringify({
  ok: true,
  apk: apkRel,
  sizeBytes: fs.statSync(apk).size,
  sha256,
  packaged: actual,
}, null, 2));
NODE

printf 'build:apk: PUSH-enabled release APK is ready: %s\n' "$APK_REL"
printf 'build:apk: nothing was copied or published.\n'

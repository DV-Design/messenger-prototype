/**
 * English is the primary UI language. Russian is selected only when the phone's
 * primary locale is Russian; every other locale falls back to English.
 */
export let locale: 'en' | 'ru' = 'en';
export let intlLocale = 'en-US';

/** Called once from the mobile entry point before app modules are evaluated. */
export function setLocale(languageCode: string | null | undefined): void {
  locale = (languageCode ?? 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
  intlLocale = locale === 'ru' ? 'ru-RU' : 'en-US';
}

